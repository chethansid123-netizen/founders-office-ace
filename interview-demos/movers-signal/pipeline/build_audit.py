"""Write AUDIT.md and data/audit.json from the pipeline outputs.

Every number here is computed from files in data/: nothing is typed by hand.

Usage:  python3 -I pipeline/build_audit.py
"""

from __future__ import annotations

import sys as _sys
from pathlib import Path as _Path
_sys.path.insert(0, str(_Path(__file__).resolve().parent))  # pipeline/ (own code only)

import sys
from collections import Counter

from common import DATA, ROOT, SNAPSHOT_DATE, WINDOW_START, load_json, now_utc, save_json


def classify(problem: str) -> str:
    if "quote not reproducible" in problem and problem.startswith(("exchange_symbol", "company")):
        return "Quote spanned two layout columns (address block)"
    if "quote not reproducible" in problem:
        return "Quote not in the independent engines' reading order (table row)"
    if "not supported word-for-word" in problem:
        return "Value not fully supported by its quote"
    if "possible successor wording" in problem:
        return "Possible successor wording in the document"
    if problem.startswith("OUT_OF_WINDOW"):
        return "Filed outside the 90-day window"
    if problem.startswith("CONFLICTING_DUPLICATE"):
        return "Same event filed twice with conflicting dates"
    return "Other"


def main() -> int:
    v1 = load_json(DATA / "verification_v1.json")
    v2 = load_json(DATA / "verification_v2.json")
    corr = load_json(DATA / "corrections_applied.json")
    final = load_json(DATA / "records.json")
    shortlist = load_json(DATA / "shortlist.json")
    manifest = load_json(DATA / "raw" / "manifest.json")
    ai = load_json(DATA / "review_decisions_ai.json")
    human = load_json(DATA / "review_decisions_human.json", None)
    recs = final["records"]

    def problems(run):
        out = []
        for rid, v in run["records"].items():
            for k, f in v["fields"].items():
                if f["status"] == "mismatch":
                    out.append((rid, f"{k}: {f['reason']}"))
            for c in v["context"]:
                if c["status"] == "mismatch":
                    out.append((rid, f"context: {c['reason']}"))
            for fl in v.get("record_flags", []):
                out.append((rid, fl))
        return out

    p1, p2 = problems(v1), problems(v2)
    field_mismatch_v1 = sum(1 for _, p in p1 if not p.startswith(("OUT_OF_WINDOW", "CONFLICTING")))
    flags_v1 = len(p1) - field_mismatch_v1
    classes = Counter(classify(p) for _, p in p1)
    verified = [r for r in recs if r["review_status"] == "VERIFIED"]
    rejected = [r for r in recs if r["review_status"] == "REJECTED"]
    overrides = [(r["id"], o) for r in recs for o in r.get("review_overrides", [])]
    fixed_ids = {(i["id"], i["field"]) for i in corr["items"]}
    v2_status = {(rid, k): f["status"] for rid, v in v2["records"].items() for k, f in v["fields"].items()}
    fixed_now_match = sum(1 for key in fixed_ids if v2_status.get(key) in ("match", "not_found"))
    filings_reviewed = len({r["source_key"] for r in recs})
    study = len(shortlist["extract"])
    tests = len(shortlist["extract_for_review_test"])
    screened = len(shortlist["screened_out"])
    fetched = sum(1 for e in manifest.values() if not e.get("error"))
    last_review = (human or {}).get("reviewed_at") or ai["reviewed_at"]

    audit = {
        "generated_at": now_utc(),
        "window": [WINDOW_START, SNAPSHOT_DATE],
        "documents_fetched": fetched,
        "filings_reviewed": filings_reviewed,
        "filings_in_study": study,
        "review_test_filings": tests,
        "screened_out_at_triage": screened,
        "fields_checked_per_run": v1["fields_checked"],
        "context_facts_checked_per_run": v1["context_facts_checked"],
        "verification_runs": 2,
        "errors_found": len(p1),
        "errors_found_fields": field_mismatch_v1,
        "errors_found_record_flags": flags_v1,
        "errors_fixed": len(corr["items"]),
        "errors_fixed_now_match": fixed_now_match,
        "false_positives_cleared": len(overrides),
        "records_rejected": len(rejected),
        "records_verified": len(verified),
        "seats_verified": len(verified),
        "filings_verified": len({r["source_key"] for r in verified}),
        "date_of_last_review": last_review,
        "reviewed_by": (human or {}).get("reviewer") or ai["reviewer"],
        "human_signoff": bool(human),
        "error_classes_v1": dict(classes),
        "open_items_v2": len(p2),
    }
    save_json(DATA / "audit.json", audit)

    L = []
    L.append("# AUDIT")
    L.append("")
    L.append(f"Generated by `pipeline/build_audit.py` from the files in `data/`. Window: filings dated "
             f"{WINDOW_START} to {SNAPSHOT_DATE}.")
    L.append("")
    L.append("| Count | Value |")
    L.append("|---|---|")
    L.append(f"| Filings reviewed | **{filings_reviewed}** ({study} in the study set, {tests} kept as review tests); "
             f"{screened} more screened out at triage; {fetched} documents fetched |")
    L.append(f"| Fields checked | **{v1['fields_checked']}** per verification run, plus "
             f"{v1['context_facts_checked']} extra filed facts (2 runs) |")
    L.append(f"| Errors found | **{len(p1)}** in run 1: {field_mismatch_v1} field mismatches and {flags_v1} record flags |")
    L.append(f"| Errors fixed | **{len(corr['items'])}** corrections; {fixed_now_match} of them re-verified as match in run 2 |")
    L.append(f"| Records rejected | **{len(rejected)}** |")
    L.append(f"| Date of last review | **{last_review}** by {audit['reviewed_by']}"
             + ("" if human else "; human sign-off pending") + " |")
    L.append("")
    L.append(f"Result: **{len(verified)} verified seats from {audit['filings_verified']} filings.** "
             f"{len(overrides)} verifier flag(s) cleared as false positives with a written reason.")
    L.append("")
    L.append("## What the verifier caught in run 1")
    L.append("")
    L.append("| Class | Count |")
    L.append("|---|---|")
    for k, n in classes.most_common():
        L.append(f"| {k} | {n} |")
    L.append("")
    L.append("## Corrections (errors fixed)")
    L.append("")
    L.append("| Record | Field | Reason |")
    L.append("|---|---|---|")
    for i in corr["items"]:
        L.append(f"| `{i['id']}` | {i['field']} | {i['reason']} |")
    L.append("")
    L.append("## False positives cleared at review")
    L.append("")
    for rid, o in overrides:
        L.append(f"- `{rid}` ({o['field']}): {o['reason']}")
    L.append("")
    L.append("## Records rejected")
    L.append("")
    L.append("| Record | Reason |")
    L.append("|---|---|")
    for r in rejected:
        L.append(f"| `{r['id']}` | {r['review_note']} |")
    L.append("")
    L.append("## Caught before extraction")
    L.append("")
    L.append("- Web search named an Ashok Leyland filing as Dr. Reddy's. The PDF (scrip ASHOKLEY, signed for Ashok Leyland) was used.")
    L.append("- Web search linked a Bain Capital (BC Asia) disclosure to Manappuram. The PDF concerns Dhoot Transmission, so it was not used.")
    L.append("- MTNL's PDF has no Unicode text layer; JK Paper's PDF is malformed on the exchange; Credent's text layer drops word spacing. All three screened out.")
    L.append("")
    L.append("## How to re-run")
    L.append("")
    L.append("```")
    L.append("python3 -I pipeline/fetch.py            # re-download PDFs (hash-checked)")
    L.append("python3 -I pipeline/textify.py          # engine A page text")
    L.append("python3 -I pipeline/build_pass1.py      # pass 1 -> data/extracted_v1.json")
    L.append("python3 -I pipeline/verify.py data/extracted_v1.json data/verification_v1.json")
    L.append("python3 -I pipeline/apply_corrections.py")
    L.append("python3 -I pipeline/verify.py data/extracted_v2.json data/verification_v2.json --queue")
    L.append("python3 -I pipeline/apply_review.py     # -> data/records.json")
    L.append("python3 -I pipeline/build_audit.py      # -> AUDIT.md, data/audit.json")
    L.append("```")
    L.append("")
    (ROOT / "AUDIT.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote AUDIT.md and data/audit.json")
    print({k: audit[k] for k in ("filings_reviewed", "fields_checked_per_run", "errors_found", "errors_fixed",
                                 "records_rejected", "date_of_last_review", "seats_verified")})
    return 0


if __name__ == "__main__":
    sys.exit(main())
